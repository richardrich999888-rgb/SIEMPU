// D-T5-01 fix evidence: full-chain (protocol v1, the baseline) versus incremental (protocol v2,
// ADR-014) custody authorisation cost, measured in one process on one commit and one machine.
// Orchestration only: the measurement is scripts/custody-scaling.mjs.
//
// Usage: node assurance/bench/d-t5-01-compare.mjs [--report FILE.md] [--json FILE.json]

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { measureCustodyScaling } from '../../scripts/custody-scaling.mjs';
import { gitRevision } from '../kat/io/sources.mjs';
import { getVersion } from '../kat/io/runtime.mjs';
import { LENGTHS, WARMUP, repeatsFor } from './d-t5-01.mjs';

/** Incremental mode is also measured beyond the v1 verifier limit (100,000 records). */
export const INCREMENTAL_LENGTHS = Object.freeze([...LENGTHS, 250000]);
/** Records appended before each timed incremental authorisation: one request's own evidence. */
export const APPEND_PER_AUTHORISATION = 4;
export const INCREMENTAL_REPEATS = 50;

/** Formats one result row as a Markdown table row (pure). */
function row(x) {
  return `| ${x.records.toLocaleString('en-US')} | ${x.recordsVerifiedPerAuthorisationMax.toLocaleString('en-US')} | ${x.repeats} | ${x.authorizeMsMedian} | ${x.authorizeMsP95} | ${x.authorizeMsMax} | ${x.authorisationsPerSecond} |`;
}

/**
 * Renders the comparison report (pure).
 * @param {{full: any, incremental: any, revision: {commit: string, dirty: boolean},
 *   command: string, startedAt: string, finishedAt: string,
 *   runtime: Record<string, string>, cpu: string}} run
 */
export function renderComparison(run) {
  const { full, incremental } = run;
  const header = [
    '| Chain length at start (records) | Records verified by custodian per authorisation (max) | Timed runs | Median (ms) | p95 (ms) | Max (ms) | Authorisations/s |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ];
  const ratio = (n) => {
    const a = full.rows.find((x) => x.records === n);
    const b = incremental.rows.find((x) => x.records === n);
    return a && b ? Math.round(a.authorizeMsMedian / b.authorizeMsMedian) : null;
  };
  return [
    '# D-T5-01 fix: full-chain versus incremental custody authorisation',
    '',
    '<!-- GENERATED by assurance/bench/d-t5-01-compare.mjs. Re-run the command below; do not edit by hand. -->',
    '',
    '**What is measured.** One `recoveryGuard.authorize()` call, in-process (no TLS, no network), for both custody protocols on the same commit, machine and run. **Full-chain** (protocol v1, the D-T5-01 baseline) ships the whole chain and the custodian re-verifies it from genesis. **Incremental** (protocol v2, ADR-014) ships only the records after the custodian anchor; the custodian verifies those and checks that they extend the anchor. Before each timed incremental authorisation the harness appends ' +
      `${incremental.rows[0]?.appendPerAuthorisation ?? APPEND_PER_AUTHORISATION} records (untimed), standing in for one request's own evidence; the full-chain rows use the baseline configuration (no appends), which favours full-chain.`,
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Command | \`${run.command}\` |`,
    `| Commit | \`${run.revision.commit}\`${run.revision.dirty ? ' (working tree had uncommitted changes)' : ' (clean working tree)'} |`,
    `| Window | ${run.startedAt} → ${run.finishedAt} |`,
    `| CPU | ${run.cpu} |`,
    ...Object.entries(run.runtime).map(([k, v]) => `| ${k} | ${v} |`),
    `| Warm-up | ${full.warmup} untimed authorisation(s) per length and mode (incremental catch-up happens here) |`,
    '',
    '## Full-chain (protocol v1, baseline behaviour)',
    '',
    ...header,
    ...full.rows.map(row),
    '',
    `Least-squares fit: **${full.fit.msPerRecord} ms per record + ${full.fit.fixedMs} ms**.`,
    '',
    '## Incremental (protocol v2, ADR-014)',
    '',
    ...header,
    ...incremental.rows.map(row),
    '',
    `Least-squares fit: **${incremental.fit.msPerRecord} ms per record + ${incremental.fit.fixedMs} ms**. A slope near zero means the cost does not depend on chain length.`,
    '',
    '## Comparison',
    '',
    '| Chain length | Median speed-up (full-chain ÷ incremental) |',
    '| --- | --- |',
    ...LENGTHS.map((n) => `| ${n.toLocaleString('en-US')} | ${ratio(n) ?? 'n/a'}× |`),
    '',
    '## Reading the numbers',
    '',
    '- The records-verified column is exact and machine-independent; the timings are not. p95 is nearest-rank over the stated number of runs.',
    '- Full-chain is not measured above 100,000 records: the verifier rejects longer exports (`Evidence export exceeds verifier record limit`), and over HTTP the custodian rejects bodies above 16 MiB (roughly 40,000 records). Under v1 the authority therefore fails closed permanently once its chain is long enough; v2 removes that cliff because each request carries at most 512 records.',
    '- Each request still performs two authorisations, serialised. Per-request cost no longer grows with history, but it is not zero: the authorization-state digest reads all users, devices and policies (O(identities)), and every authorisation makes one custodian round trip.',
    '- The one-time catch-up after an authority or custodian restart verifies the records since the last anchor, in bounded batches; it is excluded from the timed runs by the warm-up.',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  const revision = gitRevision(resolve('.'));
  const startedAt = new Date().toISOString();
  const incremental = await measureCustodyScaling([...INCREMENTAL_LENGTHS], {
    mode: 'incremental',
    repeats: INCREMENTAL_REPEATS,
    warmup: WARMUP,
    appendPerAuthorisation: APPEND_PER_AUTHORISATION,
  });
  const full = await measureCustodyScaling([...LENGTHS], {
    mode: 'full-chain',
    repeats: repeatsFor,
    warmup: WARMUP,
  });
  const { cpus } = await import('node:os');
  const run = {
    full,
    incremental,
    revision,
    command: `node assurance/bench/d-t5-01-compare.mjs ${args.join(' ')}`.trim(),
    startedAt,
    finishedAt: new Date().toISOString(),
    runtime: getVersion(),
    cpu: `${cpus().length} × ${cpus()[0]?.model ?? 'unknown'}`,
  };
  for (const r of [...full.rows, ...incremental.rows])
    console.log(
      `${r.mode} ${r.records}: median ${r.authorizeMsMedian} ms, verified ${r.recordsVerifiedPerAuthorisationMax} records`,
    );
  const i = args.indexOf('--report');
  if (i !== -1) writeFileSync(args[i + 1], renderComparison(run));
  const j = args.indexOf('--json');
  if (j !== -1) writeFileSync(args[j + 1], JSON.stringify(run, null, 2) + '\n');
}
