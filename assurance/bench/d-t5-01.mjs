// Baseline benchmark for defect D-T5-01: cost of one recovery-guard authorisation (authority ->
// independent custodian, full evidence-chain re-verification) versus chain length.
// Orchestration only: the measurement is scripts/custody-scaling.mjs; production code is not
// changed or wrapped.
//
// Usage: node assurance/bench/d-t5-01.mjs [--report docs/assurance/d-t5-01-baseline.md]

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { measureCustodyScaling } from '../../scripts/custody-scaling.mjs';
import { gitRevision } from '../kat/io/sources.mjs';
import { getVersion } from '../kat/io/runtime.mjs';

/** Chain lengths from the request (1k, 10k, 100k records). */
export const LENGTHS = Object.freeze([1000, 10000, 100000]);
/** Timed authorisations per length: fewer at 100k because each one takes seconds. */
export const repeatsFor = (records) => (records >= 100000 ? 10 : 20);
export const WARMUP = 1;

/**
 * Renders the baseline report (pure).
 * @param {{result: any, revision: {commit: string, dirty: boolean}, command: string,
 *   startedAt: string, finishedAt: string, runtime: Record<string,string>, cpu: string}} run
 */
export function renderBaseline(run) {
  const r = run.result;
  const out = [
    '# D-T5-01 baseline: custody authorisation cost versus evidence-chain length',
    '',
    '<!-- GENERATED by assurance/bench/d-t5-01.mjs. Re-run the command below; do not edit by hand. -->',
    '',
    '**What is measured.** One `recoveryGuard.authorize()` call (`services/evidence/custody.mjs`): the authority snapshots its whole evidence chain, signs a checkpoint request, and the independent custodian re-verifies every record signature from genesis (`verifyEvidence`) before anchoring the head. `Authority.dispatch` performs **two** such calls per request, serialised across all requests (`services/control/core.mjs`). Measured in-process (no TLS, no network), so the deployed path is slower. Production code is unchanged.',
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Command | \`${run.command}\` |`,
    `| Commit | \`${run.revision.commit}\`${run.revision.dirty ? ' (working tree had uncommitted changes)' : ' (clean working tree)'} |`,
    `| Window | ${run.startedAt} → ${run.finishedAt} |`,
    `| CPU | ${run.cpu} |`,
    ...Object.entries(run.runtime).map(([k, v]) => `| ${k} | ${v} |`),
    `| Warm-up | ${r.warmup} untimed authorisation(s) per length |`,
    '',
    '## Results',
    '',
    '| Chain length (records) | Timed runs | Median (ms) | Mean (ms) | p95 (ms) | Max (ms) | Authorisations/s | Upper bound, requests/s (= authorisations/s ÷ 2) |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...r.rows.map(
      (x) =>
        `| ${x.records.toLocaleString('en-US')} | ${x.repeats} | ${x.authorizeMsMedian} | ${x.authorizeMsMean} | ${x.authorizeMsP95} | ${x.authorizeMsMax} | ${x.authorisationsPerSecond} | ${Math.round((x.authorisationsPerSecond / 2) * 100) / 100} |`,
    ),
    '',
    `Least-squares fit over these rows: **${r.fit.msPerRecord} ms per record + ${r.fit.fixedMs} ms** per authorisation.`,
    '',
    '## Reading the numbers',
    '',
    '- p95 uses the nearest-rank method. With 10 or 20 timed runs, p95 is the largest or second-largest sample; treat it as indicative.',
    '- "Requests/s" is a ceiling for the whole authority, because dispatch is serialised and each request needs two authorisations. It ignores the request\'s own work, TLS and the network, so real throughput is lower.',
    "- **Seed.** The request asked for a fixed seed. The workload contains no randomness under the harness's control: chain content is a fixed event type repeated N times. Authority and custodian keys are generated by OpenSSL, and event IDs and checkpoint nonces come from `randomUUID` inside production code that must not change. These values do not affect the amount of work. Variation between runs is scheduling and JIT noise, which the repeated samples expose (`samplesMs` in the JSON output).",
    '',
    '## Status',
    '',
    'This is a baseline for the open defect D-T5-01 (`docs/trl5/PERFORMANCE_REPORT.md`). The proposed fix is incremental checkpoints (gap-analysis task A-14). It is not implemented, and nothing here changes production code.',
    '',
  ];
  return out.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  const root = resolve('.');
  const revision = gitRevision(root);
  const startedAt = new Date().toISOString();
  const result = await measureCustodyScaling([...LENGTHS], { repeats: repeatsFor, warmup: WARMUP });
  const { cpus } = await import('node:os');
  const run = {
    result,
    revision,
    command: `node assurance/bench/d-t5-01.mjs ${args.join(' ')}`.trim(),
    startedAt,
    finishedAt: new Date().toISOString(),
    runtime: getVersion(),
    cpu: `${cpus().length} × ${cpus()[0]?.model ?? 'unknown'}`,
  };
  for (const x of result.rows)
    console.log(
      `${x.records} records: median ${x.authorizeMsMedian} ms, p95 ${x.authorizeMsP95} ms, ${x.authorisationsPerSecond} authorisations/s`,
    );
  const i = args.indexOf('--report');
  if (i !== -1) writeFileSync(args[i + 1], renderBaseline(run));
  const j = args.indexOf('--json');
  if (j !== -1) writeFileSync(args[j + 1], JSON.stringify(run, null, 2) + '\n');
}
