import test from 'node:test';
import assert from 'node:assert/strict';
import { coreFixture } from './helpers/fixture.mjs';
import { pair, createObject, enrollUser, hash, canonical } from './helpers/client.mjs';
import {
  CheckpointCustodian,
  createRecoveryGuard,
  authorizationDigest,
} from '../services/evidence/custody.mjs';

async function guarded(t, incremental) {
  const f = await coreFixture(t);
  const keys = pair();
  const custody = new CheckpointCustodian({
    database: ':memory:',
    authorityKey: f.provisioned.serverPublicKey,
    signingKey: keys.privateKey,
    allowBootstrap: true,
  });
  t.after(() => custody.close());
  const makeGuard = (exchange = (r) => custody.accept(r)) =>
    createRecoveryGuard({
      custodianKey: keys.publicKey,
      exchange,
      ...(incremental ? { anchorQuery: (r) => custody.anchor(r) } : {}),
    });
  f.authority.recoveryGuard = makeGuard();
  for (const name of ['admin', 'alice', 'bob']) await f.clients[name].authenticate();
  return { ...f, custody, makeGuard };
}

for (const incremental of [false, true]) {
  const mode = incremental ? 'incremental' : 'full-chain';
  test(`${mode}: authentic unanchored failure event cannot conceal selectively restored crypto policy`, async (t) => {
    const f = await guarded(t, incremental);
    const object = createObject(f.profiles.alice, f.profiles.bob, await f.clients.alice.grant());
    await f.clients.alice.submit(object);
    await f.clients.alice.prepare(object.envelope.objectId);
    const allowed = f.authority.get('SELECT value FROM crypto_policy WHERE id=1').value;
    const policy = { ...JSON.parse(allowed), revision: 2, newSuites: [], legacySuites: [] };
    assert.equal(
      (await f.clients.admin.admin('PUT', '/api/admin/crypto/policy', { policy })).status,
      200,
    );
    let exchanges = 0;
    f.authority.recoveryGuard = f.makeGuard((r) => {
      if (++exchanges > 1) throw new Error('PARTITION_AFTER_LOCAL_COMMIT');
      return f.custody.accept(r);
    });
    assert.equal(
      (
        await f.clients.bob.request('POST', '/api/auth/login', {
          username: 'alice',
          password: 'wrong-password',
          otp: '000000',
        })
      ).status,
      503,
    );
    const retained = JSON.parse(
      f.custody.db.prepare('SELECT checkpoint FROM anchor').get().checkpoint,
    ).payload;
    assert.ok(f.authority.checkpoint().payload.sequence > retained.sequence);
    f.authority.run('UPDATE crypto_policy SET value=? WHERE id=1', allowed);
    f.authority.recoveryGuard = f.makeGuard();
    await assert.rejects(
      f.clients.bob.claim(object.envelope.objectId, f.authority.epoch().epoch),
      /503.*RECOVERY_QUARANTINED/,
    );
    assert.equal(f.authority.recoveryGuard.reason, 'AUTHORIZATION_COMMIT_MISMATCH');
    assert.equal(f.authority.get('SELECT count(*) n FROM issuances').n, 0);
    f.authority.run('UPDATE crypto_policy SET value=? WHERE id=1', canonical(policy));
    const denied = await f.clients.bob.claim(object.envelope.objectId, f.authority.epoch().epoch);
    assert.equal(denied.body.code, 'CRYPTO_SUITE_FORBIDDEN');
  });

  test(`${mode}: missing or tampered commit seal is never regenerated by recovery or guarded writes`, async (t) => {
    const f = await guarded(t, incremental);
    const saved = f.authority.get('SELECT seal FROM authorization_commit').seal;
    f.authority.run('DELETE FROM authorization_commit');
    assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 503);
    assert.throws(
      () => f.authority.tx(() => f.authority.event('SHOULD_NOT_COMMIT', 'test')),
      /COMMIT_MISSING/,
    );
    assert.equal(f.authority.get('SELECT count(*) n FROM authorization_commit').n, 0);
    const altered = JSON.parse(saved);
    altered.payload.stateDigest = 'f'.repeat(64);
    f.authority.run('INSERT INTO authorization_commit VALUES(1,?)', canonical(altered));
    assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 503);
    f.authority.run('UPDATE authorization_commit SET seal=? WHERE id=1', saved);
    assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 200);
  });

  test(`${mode}: seal persistence failure rolls back state and evidence in the same transaction`, async (t) => {
    const f = await guarded(t, incremental);
    const before = {
      digest: authorizationDigest(f.authority),
      head: f.authority.checkpoint().payload.headHash,
    };
    f.authority.db.exec(
      "CREATE TRIGGER fail_seal BEFORE UPDATE ON authorization_commit BEGIN SELECT RAISE(ABORT, 'SEAL_DISK_FAILURE'); END",
    );
    assert.throws(
      () =>
        f.authority.tx(() => {
          f.authority.run('UPDATE authority SET epoch=epoch+1 WHERE id=1');
          f.authority.event('SYNTHETIC_INTERRUPTED_TRANSACTION', 'test');
        }),
      /SEAL_DISK_FAILURE/,
    );
    assert.equal(authorizationDigest(f.authority), before.digest);
    assert.equal(f.authority.checkpoint().payload.headHash, before.head);
    f.authority.db.exec('DROP TRIGGER fail_seal');
    assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 200);
  });
  test(`${mode}: crypto-policy rollback cannot re-enable a forbidden release`, async (t) => {
    const f = await guarded(t, incremental);
    const object = createObject(f.profiles.alice, f.profiles.bob, await f.clients.alice.grant());
    await f.clients.alice.submit(object);
    await f.clients.alice.prepare(object.envelope.objectId);
    const permitted = f.authority.get('SELECT value FROM crypto_policy WHERE id=1').value;
    const policy = { ...JSON.parse(permitted), revision: 2, newSuites: [], legacySuites: [] };
    assert.equal(
      (await f.clients.admin.admin('PUT', '/api/admin/crypto/policy', { policy })).status,
      200,
    );
    assert.equal(f.authority.crypto.reason(object.envelope), 'CRYPTO_SUITE_FORBIDDEN');
    const head = f.authority.checkpoint().payload.headHash;
    const before = authorizationDigest(f.authority);
    f.authority.run('UPDATE crypto_policy SET value=? WHERE id=1', permitted);
    assert.equal(f.authority.checkpoint().payload.headHash, head);
    assert.notEqual(authorizationDigest(f.authority), before);
    await assert.rejects(
      f.clients.bob.claim(object.envelope.objectId, f.authority.epoch().epoch),
      /503.*RECOVERY_QUARANTINED/,
    );
    assert.equal(f.authority.get('SELECT count(*) n FROM issuances').n, 0);
    // Restoring the exact anchored state resumes legitimate denial, without re-seeding custody.
    f.authority.run('UPDATE crypto_policy SET value=? WHERE id=1', canonical(policy));
    const denied = await f.clients.bob.claim(object.envelope.objectId, f.authority.epoch().epoch);
    assert.equal(denied.status, 409);
    assert.equal(denied.body.code, 'CRYPTO_SUITE_FORBIDDEN');
  });

  test(`${mode}: logged-out session and consumed proof rollback are quarantined`, async (t) => {
    const f = await guarded(t, incremental);
    const bob = f.clients.bob;
    const session = f.authority.authenticate(bob.token).id;
    assert.equal((await bob.request('POST', '/api/auth/logout', {})).status, 200);
    assert.equal((await bob.request('GET', '/api/control')).status, 401);
    f.authority.run('UPDATE sessions SET revoked=0 WHERE id=?', session);
    assert.equal((await bob.request('GET', '/api/control')).status, 503);
    f.authority.run('UPDATE sessions SET revoked=1 WHERE id=?', session);
    const proof = await f.clients.alice.proof('grant');
    assert.equal((await f.clients.alice.request('POST', '/api/grants', { proof })).status, 200);
    f.authority.run('UPDATE challenges SET used=0 WHERE id=?', proof.challengeId);
    const replay = await f.clients.alice.request('POST', '/api/grants', { proof });
    assert.equal(replay.status, 503);
    assert.equal(replay.body.code, 'RECOVERY_QUARANTINED');
    f.authority.run('UPDATE challenges SET used=1 WHERE id=?', proof.challengeId);
    assert.equal((await f.clients.alice.request('POST', '/api/grants', { proof })).status, 403);
  });

  test(`${mode}: credentials, MFA floor, runtime gate and crypto key records are bound`, async (t) => {
    const f = await guarded(t, incremental);
    const user = f.authority.get('SELECT * FROM users WHERE id=?', f.profiles.alice.userId);
    for (const [column, value] of [
      ['password', user.password + 'changed'],
      ['totp', user.totp + 'changed'],
      ['totp_floor', -1],
      ['username', 'changed-login-name'],
    ]) {
      // Column names are fixed test literals, never request-derived SQL.
      f.authority.run(`UPDATE users SET ${column}=? WHERE id=?`, value, user.id);
      assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 503, column);
      f.authority.run(`UPDATE users SET ${column}=? WHERE id=?`, user[column], user.id);
      assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 200);
    }
    f.authority.crypto.allowPqcLab = true;
    assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 503);
    f.authority.crypto.allowPqcLab = false;
    f.authority.run(
      'INSERT INTO crypto_keys VALUES(?,?,?,?,?)',
      'a'.repeat(64),
      f.profiles.alice.deviceId,
      '{}',
      'active',
      Date.now(),
    );
    assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 503);
    f.authority.run('DELETE FROM crypto_keys WHERE key_id=?', 'a'.repeat(64));
    assert.equal((await f.clients.alice.request('GET', '/api/control')).status, 200);
  });

  test(`${mode}: forged FLASH approval row cannot authorize release`, async (t) => {
    const f = await guarded(t, incremental);
    const commander = await enrollUser(f.clients.admin, {
      username: 'independent-commander',
      unitId: f.profiles.alice.unitId,
    });
    assert.equal(
      (
        await f.clients.admin.admin('PATCH', '/api/admin/users/' + commander.profile.userId, {
          dutyRole: 'UNIT_COMMANDER',
        })
      ).status,
      200,
    );
    const object = createObject(f.profiles.alice, f.profiles.bob, await f.clients.alice.grant(), {
      context: { schemaVersion: 2, messagePriority: 'FLASH', messageDomain: 'GENERAL' },
    });
    await f.clients.alice.submit(object);
    const id = object.envelope.objectId,
      epoch = f.authority.epoch().epoch;
    assert.equal((await f.clients.bob.claim(id, epoch)).body.code, 'FLASH_APPROVAL_REQUIRED');
    f.authority.run(
      'INSERT INTO release_approvals VALUES(?,?,?,?,?,?,?)',
      id,
      hash(canonical(object.envelope)),
      epoch,
      commander.profile.userId,
      commander.profile.deviceId,
      Date.now(),
      '{}',
    );
    await assert.rejects(f.clients.bob.claim(id, epoch), /503.*RECOVERY_QUARANTINED/);
    assert.equal(f.authority.get('SELECT count(*) n FROM issuances').n, 0);
    f.authority.run('DELETE FROM release_approvals WHERE object_id=?', id);
    const body = { expectedDigest: hash(canonical(object.envelope)), expectedEpoch: epoch };
    const approved = await commander.client.request('POST', `/api/objects/${id}/authorize`, {
      ...body,
      proof: await commander.client.proof('authorize:' + id, body),
    });
    assert.equal(approved.status, 200);
    assert.equal((await f.clients.bob.claim(id, epoch)).status, 200);
  });
}
